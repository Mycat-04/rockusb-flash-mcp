const exec = promisify(execFile);
const usbRoot = '/sys/bus/usb/devices';

async function adbCommand(adb, args) {
  // A remote ADB server would describe a different host's USB ports.
  const env = {...process.env};
  for (const key of Object.keys(env)) {
    if (['ADB_SERVER_SOCKET','ANDROID_ADB_SERVER_ADDRESS','ANDROID_ADB_SERVER_PORT','ANDROID_SERIAL'].includes(key.toUpperCase())) delete env[key];
  }
  const {stdout} = await exec(adb, ['-P','5037',...args], {
    env, windowsHide:true, timeout:12000, maxBuffer:256*1024
  });
  return stdout.trim();
}

export function parseAdbDevices(output) {
  if (!/^List of devices attached\s*$/m.test(output)) throw Error('Unrecognized adb devices output.');
  return output.trim().split(/\r?\n/).slice(1).filter(line => line.trim()).map(line => {
    const [serial, state] = line.trim().split(/\s+/);
    const transport_id = line.match(/\btransport_id:(\d+)\b/)?.[1];
    return {serial, state, transport_id};
  });
}

export async function listAdbDevices(adb) {
  return parseAdbDevices(await adbCommand(adb, ['devices','-l']));
}

// Composite ADB interfaces and RockUSB may have different Windows instance IDs.
// LocationPaths on their physical USB parent survive USB re-enumeration.
const windowsProbe = String.raw`
$ErrorActionPreference='Stop'
$rows = @(Get-CimInstance Win32_PnPEntity -Filter "PNPDeviceID LIKE 'USB%'" | ForEach-Object {
  $id = $_.PNPDeviceID
  if ($_.Present -and $id -match '^USB\\VID_([0-9A-F]{4})&PID_([0-9A-F]{4})') {
    $vid = '0x'+$Matches[1].ToLower()
    $pidValue = '0x'+$Matches[2].ToLower()
    $adb = [bool]($_.CompatibleID -match 'Class_ff&SubClass_42&Prot_01$')
    if ($adb -or $vid -eq '0x2207') {
      $locations = (Get-PnpDeviceProperty -InstanceId $id -KeyName DEVPKEY_Device_LocationPaths).Data
      $port = $locations | ForEach-Object { $_ -replace '#USBMI\(\d+\)$','' } | Where-Object { $_ -match '#USB\(\d+\)$' } | Select-Object -First 1
      # An instance suffix with ampersands is generated by Windows for this port.
      $serial = if ($id -match '^USB\\VID_[0-9A-F]{4}&PID_[0-9A-F]{4}\\([^&\\]+)$') { $Matches[1] }
      [PSCustomObject]@{port=$port;vid=$vid;pid=$pidValue;adb=$adb;serial=$serial}
    }
  }
})
ConvertTo-Json -Compress -InputObject $rows`;

async function usbPorts() {
  let rows;
  if (process.platform === 'win32') {
    const ps = path.join(process.env.SystemRoot,'System32/WindowsPowerShell/v1.0/powershell.exe');
    const {stdout} = await exec(ps, ['-NoProfile','-NonInteractive','-EncodedCommand',Buffer.from(windowsProbe,'utf16le').toString('base64')],
      {windowsHide:true,timeout:12000});
    rows = JSON.parse(stdout);
  } else if (process.platform === 'linux') {
    const entries = await readdir(usbRoot);
    const attr = async (entry, key) => (await readFile(path.join(usbRoot,entry,key),'utf8')).trim();
    rows = await Promise.all(entries.filter(name => /^\d+-[\d.]+$/.test(name)).map(async port => {
      const [vid,pid] = await Promise.all(['idVendor','idProduct'].map(key => attr(port,key)));
      const interfaces = entries.filter(name => name.startsWith(port+':'));
      const classes = await Promise.all(interfaces.map(async name =>
        (await Promise.all(['bInterfaceClass','bInterfaceSubClass','bInterfaceProtocol'].map(key => attr(name,key)))).join(':')));
      const serial = await attr(port,'serial').catch(error => {
        if (error.code !== 'ENOENT') throw error;
      });
      return {port,vid:'0x'+vid,pid:'0x'+pid,adb:classes.includes('ff:42:01'),serial};
    }));
  } else {
    throw Error('Loader switching requires a Windows or Linux USB host.');
  }
  const ports = new Map();
  for (const row of rows) {
    if (!row.port) throw Error('Cannot identify a physical USB port for an attached device.');
    const prior = ports.get(row.port);
    if (prior && (prior.vid !== row.vid || prior.pid !== row.pid)) throw Error('USB topology changed during enumeration.');
    ports.set(row.port,{...row,adb:row.adb || !!prior?.adb,serial:row.serial || prior?.serial});
  }
  return [...ports.values()];
}

const host = {listAdbDevices, adbCommand, usbPorts, listDevices, sleep, now:Date.now};

export async function identifyAdb(adb, serial, io = host) {
  const transports = (await io.listAdbDevices(adb)).filter(row => row.serial === serial);
  if (transports.length !== 1 || transports[0].state !== 'device' || !transports[0].transport_id)
    throw Error('Select one authorized ADB serial with a transport_id from list_devices.');
  const ports = (await io.usbPorts()).filter(row => row.adb);
  let usb;
  if (ports.length === 1) {
    if (await io.adbCommand(adb,['-d','get-serialno']) !== serial)
      throw Error('The selected ADB serial does not match the local USB transport.');
    usb = ports[0];
  } else if (ports.length > 1 && !/:|^emulator-|_tcp\.?$/i.test(serial)) {
    const devpath = await io.adbCommand(adb,['-t',transports[0].transport_id,'get-devpath']);
    const matches = ports.filter(row => row.serial?.toUpperCase() === serial.toUpperCase());
    // Linux provides the physical bus-port chain. On Windows ADB often returns "unknown".
    usb = ports.find(row => 'usb:'+row.port === devpath);
    if (usb && matches.length === 1 && matches[0].port !== usb.port)
      throw Error('ADB and the USB descriptor identify different ports. Reconnect the target board and list devices again.');
    if (!usb && (devpath === 'unknown' || !devpath) && matches.length === 1) usb = matches[0];
  }
  if (!usb || usb.vid !== '0x2207')
    throw Error('Cannot bind the chosen ADB serial to a unique Rockchip USB port. Leave only the target USB ADB board connected and list devices again.');
  return {...transports[0],port:usb.port,pid:usb.pid};
}

export function rockusbAtPort(port, ports, devices) {
  const usb = ports.find(row => row.port === port);
  if (!usb || usb.adb || usb.vid !== '0x2207') return;
  // upgrade_tool's LocationID uses a different numbering scheme from the OS.
  // Use a shared serial when more than one board has this VID:PID.
  const sameType = row => row.vid === usb.vid && row.pid === usb.pid;
  const matches = devices.filter(sameType);
  if (ports.filter(sameType).length === 1 && matches.length === 1) {
    const device = matches[0];
    if (usb.serial && device.serial && usb.serial.toUpperCase() !== device.serial.toUpperCase()) return;
    return device;
  }
  if (usb.serial && ports.filter(sameType).filter(row => row.serial?.toUpperCase() === usb.serial.toUpperCase()).length === 1) {
    const selected = matches.filter(row => row.serial?.toUpperCase() === usb.serial.toUpperCase());
    if (selected.length === 1) return selected[0];
  }
}

export async function enterLoader(plan, onStatus, io = host) {
  await io.listDevices(plan.backend); // Ensure Loader verification is available before interrupting the board.
  const target = await identifyAdb(plan.adb,plan.device.serial,io);
  for (const key of ['port','pid','transport_id']) {
    if (target[key] !== plan.device[key]) throw Error('The approved ADB transport or USB port changed. Prepare a new plan.');
  }
  if (await io.adbCommand(plan.adb,['-t',target.transport_id,'get-serialno']) !== target.serial)
    throw Error('The selected transport no longer has the approved ADB serial.');
  await onStatus('rebooting','Requesting Loader on USB port '+target.port+'.');
  let detail = '';
  try {
    await io.adbCommand(plan.adb,['-t',target.transport_id,'shell','reboot','loader']);
  } catch (error) {
    // The shell can disappear before it acknowledges a successful reboot.
    detail = error.stderr?.trim() || error.message;
  }
  await onStatus('waiting_for_loader','Waiting for RockUSB Loader on '+target.port+'.');
  const deadline = io.now()+60000;
  do {
    let device;
    try {
      const [ports,devices] = await Promise.all([io.usbPorts(),io.listDevices(plan.backend)]);
      device = rockusbAtPort(target.port,ports,devices);
    } catch (error) { detail = error.message; }
    if (device?.mode === 'loader') return device;
    if (device?.mode === 'maskrom') throw Error('The selected USB port entered Maskrom instead of Loader.');
    await io.sleep(1000);
  } while (io.now() < deadline);
  throw Error('Loader was not verified on the selected USB port. Check list_devices, the USB driver and the board reboot support before retrying.'+(detail?' Last diagnostic: '+detail:''));
}
